// 見積書のタイトル(名前)から、「調査・内装・その他」の分類を判断する。
// 工事は、ほとんどの見積が当てはまるので、分類にはしない(「すべて」と、その他の中に入る)。
// 案件や見積に分類の列を持たせず、タイトルの言葉だけで毎回判断する(DBの変更なし)。
//
// 判断の順番(上から順に、最初に当てはまったものにする):
//   1. タイトルに「調査」が入っている → 調査
//   2. タイトルに「内装」が入っている → 内装
//   3. どれにも当てはまらない → その他(「〇〇工事」はここに入る)
// 分け方を変えたいときは、下のRULESの並びと言葉だけを直せばよい。

export const QUOTE_CATEGORIES = ["調査", "内装", "その他"];

const RULES = [
  ["調査", ["調査"]],
  ["内装", ["内装"]],
];

export function quoteCategory(title) {
  const t = String(title || "");
  for (const [cat, words] of RULES) {
    if (words.some(w => t.includes(w))) return cat;
  }
  return "その他";
}
